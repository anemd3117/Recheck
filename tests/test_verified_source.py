"""Source identity must describe the very files that passed verification."""
import importlib
import hashlib
import json
import subprocess

import pytest


def test_tests_changing_runtime_source_cannot_receive_verified_identity(tmp_path):
    assert importlib.util.find_spec('scripts.verify_source'), 'source verification entrypoint missing'
    m = importlib.import_module('scripts.verify_source')
    (tmp_path / 'recheck').mkdir()
    path = tmp_path / 'recheck/__init__.py'
    path.write_text("__version__ = '1.2.0-prototype.2'\n")

    def run(command, **kwargs):
        path.write_text("__version__ = 'changed during tests'\n")
        return subprocess.CompletedProcess(command, 0)

    with pytest.raises(ValueError, match='changed'):
        m.verify(tmp_path, tmp_path / 'records', runner=run)
    assert not (tmp_path / 'RECHECK_SOURCE_IDENTITY.json').exists()


@pytest.mark.parametrize('name,change', [
    ('tests/test_example.py', 'modify'),
    ('tests/test_added.py', 'add'),
    ('tests/test_example.py', 'delete'),
    ('.github/workflows/tests.yml', 'modify'),
    ('.github/workflows/security.yml', 'modify'),
    ('.github/workflows/new-check.yml', 'add'),
    ('requirements-quality.txt', 'modify'),
    ('conftest.py', 'modify'),
    ('pytest.ini', 'modify'),
    ('pytest.toml', 'modify'),
    ('.pytest.toml', 'add'),
    ('.pytest.ini', 'modify'),
])
def test_changed_verification_inputs_preserve_previous_identity(tmp_path, name, change):
    m = importlib.import_module('scripts.verify_source')
    make_verifiable_project(tmp_path)
    changed = tmp_path / name
    changed.parent.mkdir(parents=True, exist_ok=True)
    if change != 'add':
        changed.write_text('reviewed check', encoding='utf-8')
    identity = tmp_path / 'RECHECK_SOURCE_IDENTITY.json'
    identity.write_bytes(b'{"previous":"verified"}\n')

    def run(command, **kwargs):
        if change == 'delete':
            changed.unlink(missing_ok=True)
        else:
            changed.write_text('changed check', encoding='utf-8')
        return subprocess.CompletedProcess(command, 0)

    with pytest.raises(ValueError, match='changed'):
        m.verify(tmp_path, tmp_path / 'records', runner=run)
    assert identity.read_bytes() == b'{"previous":"verified"}\n'
    assert not (tmp_path / 'records/verified-source.json').exists()


def make_verifiable_project(root):
    (root / 'recheck').mkdir()
    (root / 'resources').mkdir()
    (root / 'recheck/__init__.py').write_text("__version__ = '1.2.5-prototype.1'\n")
    (root / 'pyproject.toml').write_text('[project]\nversion="1.2.5a1"\n')
    (root / 'resources/version_info.txt').write_text('filevers=(1,2,5,1)')


def test_success_records_checks_separately_from_runtime_identity(tmp_path):
    m = importlib.import_module('scripts.verify_source')
    make_verifiable_project(tmp_path)
    (tmp_path / 'tests').mkdir()
    (tmp_path / 'tests/test_example.py').write_bytes(b'assert True\n')

    def run(command, **kwargs):
        # Generated bytecode is not a change to the checks themselves.
        cache = tmp_path / 'tests/__pycache__'
        cache.mkdir(exist_ok=True)
        (cache / 'test_example.pyc').write_bytes(b'generated')
        return subprocess.CompletedProcess(command, 0)

    result = m.verify(tmp_path, tmp_path / 'records', runner=run)
    verification = result['verification']
    assert verification['inputs']['tests/test_example.py'] == hashlib.sha256(b'assert True\n').hexdigest()
    assert not any(name.startswith('tests/') for name in result['runtime_identity'])
    assert not any('__pycache__' in name for name in verification['inputs'])
    assert [row['returncode'] for row in verification['commands']] == [0, 0]
    assert verification['commands'][0]['argv'][1:3] == ['-m', 'pytest']
    assert verification['commands'][1]['argv'][0:2] == ['node', '--test']
    assert verification['environment']['QT_QPA_PLATFORM'] == 'offscreen'
    assert verification['environment']['RECHECK_DATA_DIR'] == str(tmp_path / 'records/test-data')
    assert json.loads((tmp_path / 'records/verified-source.json').read_text(encoding='utf-8')) == result


def test_failed_verification_preserves_existing_source_identity(tmp_path):
    assert importlib.util.find_spec('scripts.verify_source'), 'source verification entrypoint missing'
    m = importlib.import_module('scripts.verify_source')
    (tmp_path / 'recheck').mkdir()
    (tmp_path / 'recheck/__init__.py').write_text("__version__ = '1.2.0-prototype.2'\n")
    identity = tmp_path / 'RECHECK_SOURCE_IDENTITY.json'
    identity.write_text(json.dumps({'old': 'verified'}))

    def run(command, **kwargs):
        return subprocess.CompletedProcess(command, 1)

    with pytest.raises(RuntimeError, match='failed'):
        m.verify(tmp_path, tmp_path / 'records', runner=run)
    assert json.loads(identity.read_text()) == {'old': 'verified'}


@pytest.mark.parametrize('launcher', ['Setup-Recheck.ps1', 'Run-Recheck.cmd'])
def test_changed_source_bootstrap_cannot_receive_verified_identity(tmp_path, launcher):
    m = importlib.import_module('scripts.verify_source')
    (tmp_path / 'recheck').mkdir()
    (tmp_path / 'resources').mkdir()
    (tmp_path / 'recheck/__init__.py').write_text("__version__ = '1.2.2-prototype.1'\n")
    (tmp_path / 'pyproject.toml').write_text('[project]\nversion="1.2.2a1"\n')
    (tmp_path / 'resources/version_info.txt').write_text('filevers=(1,2,2,1)')
    bootstrap = tmp_path / launcher
    bootstrap.write_text('original reviewed bootstrap')

    def run(command, **kwargs):
        bootstrap.write_text('changed during tests')
        return subprocess.CompletedProcess(command, 0)

    with pytest.raises(ValueError, match='changed'):
        m.verify(tmp_path, tmp_path / 'records', runner=run)
    assert not (tmp_path / 'RECHECK_SOURCE_IDENTITY.json').exists()
